def print_daily_action_report(daily_summary: list, last_n_days: int = 30, strategy_name: str = ""):
    """在終端機輸出最近 N 天的操作報告"""
    if not daily_summary:
        return
    
    print("\n" + "=" * 110)
    print(f"📅 每日操作報告 ({strategy_name}) - 最近 {last_n_days} 天")
    print("=" * 110)
    print(f"{'日期':<12} {'AI操作':<6} {'價格':>10} {'買入信心':>10} {'賣出信心':>10} {'2x模式':>6} {'備註':<35}")
    print("-" * 110)
    
    for row in daily_summary[-last_n_days:]:
        icon = {'BUY': '✅', 'SELL': '🔴', 'HOLD': '⏸️'}.get(row['ai_action'], '❓')
        date_str = row['date'].strftime('%Y-%m-%d')
        price_str = f"{row['price']:,.0f}"
        
        buy_conf_str = f"{row['ai_buy_conf']*100:.1f}%" if row['ai_buy_conf'] is not None else "-"
        sell_conf_str = f"{row['ai_sell_conf']*100:.1f}%" if row['ai_sell_conf'] is not None else "-"
        
        # 槓桿模式狀態 (如果有的話)
        lev_mode = row.get('leveraged_mode', None)
        lev_str = "🔥2x" if lev_mode else ("1x" if lev_mode is not None else "-")
        
        print(f"{date_str:<12} {icon} {row['ai_action']:<4} {price_str:>10} {buy_conf_str:>10} {sell_conf_str:>10} {lev_str:>6}  {row['note']:<35}")
    
    print("=" * 110)
    
    # 統計
    recent = daily_summary[-last_n_days:]
    total_days = len(recent)
    buy_count = sum(1 for r in recent if r['ai_action'] == 'BUY')
    sell_count = sum(1 for r in recent if r['ai_action'] == 'SELL')
    hold_count = total_days - buy_count - sell_count
    
    # 最後一天的總倉數
    final_total = recent[-1]['total_position_count'] if recent else 0
    final_dca = recent[-1]['dca_position_count'] if recent else 0
    final_ai = recent[-1]['ai_position_count'] if recent else 0
    final_2x = recent[-1].get('positions_2x', 0) if recent else 0
    
    print(f"統計: 總天數 {total_days} | AI買入 {buy_count} 倉 | AI賣出 {sell_count} 倉 | HOLD {hold_count} 天")
    print(f"最終持倉: 總 {final_total} 倉 (DCA {final_dca} + AI {final_ai}) | 其中 2x 槓桿: {final_2x} 倉")
    print("=" * 110)


def create_daily_timeline_chart(daily_summary: list, price_df: pd.DataFrame, save_path: str, leverage_periods: list = None):
    """產生每日操作時間線圖表：價格走勢+買賣點、總倉數時序"""
    if not daily_summary:
        return
    
    summary_df = pd.DataFrame(daily_summary)
    summary_df.set_index('date', inplace=True)
    
    fig, axes = plt.subplots(2, 1, figsize=(16, 10), gridspec_kw={'height_ratios': [3, 1]})
    
    # 1. 價格走勢 + AI/DCA 買賣點標記 (不顯示信心度)
    ax1 = axes[0]
    
    # 標示 2x 槓桿期間 (背景色)
    if leverage_periods:
        for idx, (start_dt, end_dt) in enumerate(leverage_periods):
            ax1.axvspan(start_dt, end_dt, alpha=0.15, color='red', 
                       label='2x Leverage Period' if idx == 0 else '')
    
    ax1.plot(price_df.index, price_df['Close'], color='black', linewidth=1, label='^TWII')
    
    # AI BUY - 區分 1x 和 2x
    buy_mask = summary_df['ai_action'] == 'BUY'
    if buy_mask.any():
        buy_data = summary_df[buy_mask]
        if 'current_leverage' in buy_data.columns:
            buy_1x = buy_data[buy_data['current_leverage'] == 1.0]
            buy_2x = buy_data[buy_data['current_leverage'] > 1.0]
            if len(buy_1x) > 0:
                ax1.scatter(buy_1x.index, buy_1x['price'], marker='^', color='green', s=80, label='AI BUY (1x)', zorder=5)
            if len(buy_2x) > 0:
                ax1.scatter(buy_2x.index, buy_2x['price'], marker='^', color='red', s=100, label='AI BUY (2x)', zorder=6)
        else:
            ax1.scatter(buy_data.index, buy_data['price'], marker='^', color='green', s=80, label='AI BUY', zorder=5)
    
    # AI SELL
    sell_mask = summary_df['ai_action'] == 'SELL'
    if sell_mask.any():
        sell_dates = summary_df[sell_mask].index
        sell_prices = summary_df[sell_mask]['price']
        ax1.scatter(sell_dates, sell_prices, marker='v', color='purple', s=80, label='AI SELL', zorder=5)
    
    # DCA BUY (dca_position_count 增加時)
    dca_positions = summary_df['dca_position_count'].values
    dca_increase = [False] + [dca_positions[i] > dca_positions[i-1] for i in range(1, len(dca_positions))]
    dca_buy_dates = summary_df.index[dca_increase]
    dca_buy_prices = summary_df.loc[dca_buy_dates, 'price']
    if len(dca_buy_dates) > 0:
        ax1.scatter(dca_buy_dates, dca_buy_prices, marker='o', color='blue', s=60, label='DCA BUY', zorder=4, alpha=0.7)
    
    title_suffix = " (with 2x Leverage on Drawdown)" if leverage_periods else ""
    ax1.set_title(f'AI & DCA Trading Signals{title_suffix}', fontsize=14)
    ax1.set_ylabel('Price')
    ax1.legend(loc='upper left', fontsize=8)
    ax1.grid(True, alpha=0.3)
    
    # 2. 倉數時序圖 (堆疊區域圖: DCA + AI)
    ax2 = axes[1]
    
    # 標示 2x 槓桿期間 (背景色)
    if leverage_periods:
        for idx, (start_dt, end_dt) in enumerate(leverage_periods):
            ax2.axvspan(start_dt, end_dt, alpha=0.15, color='red')
    
    dates = summary_df.index
    dca_pos = summary_df['dca_position_count'].values
    ai_pos = summary_df['ai_position_count'].values
    total_pos = summary_df['total_position_count'].values
    
    # 堆疊區域圖
    ax2.fill_between(dates, 0, dca_pos, alpha=0.6, color='blue', label='DCA 倉')
    ax2.fill_between(dates, dca_pos, total_pos, alpha=0.6, color='green', label='AI 倉')
    ax2.plot(dates, total_pos, color='black', linewidth=1.5, label='總倉數')
    
    # 如果有 2x 倉位資訊，也顯示
    if 'positions_2x' in summary_df.columns:
        pos_2x = summary_df['positions_2x'].values
        ax2.plot(dates, pos_2x, color='red', linewidth=1.5, linestyle='--', label='2x 倉數')
    
    # 標示最終倉數
    final_total = total_pos[-1]
    final_dca = dca_pos[-1]
    final_ai = ai_pos[-1]
    final_2x = summary_df['positions_2x'].iloc[-1] if 'positions_2x' in summary_df.columns else 0
    
    label_text = f'總{final_total}倉\n(DCA{final_dca}+AI{final_ai})'
    if final_2x > 0:
        label_text += f'\n[2x:{final_2x}]'
    
    ax2.annotate(label_text, 
                (dates[-1], final_total), 
                textcoords="offset points", xytext=(10, 0), 
                ha='left', fontsize=10, fontweight='bold',
                bbox=dict(boxstyle='round', facecolor='wheat', alpha=0.8))
    
    ax2.set_ylabel('Position Count (倉數)')
    ax2.set_xlabel('Date')
    ax2.legend(loc='upper left')
    ax2.grid(True, alpha=0.3)
    ax2.set_ylim(0, max(total_pos) * 1.15)
    
    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches='tight')
    print(f"[Output] Daily Timeline Chart: {save_path}")
    plt.close()


def generate_end_date_summary(bt1, twii_df, start_date, end_date, buy_model, sell_model, 
                               feature_cols, regime_history, sell_threshold, buy_consensus_threshold, kd_threshold, bt2=None):
    """生成回測結束日摘要報告 (end_date_summary_YYYYMMDD_YYYYMMDD.txt)"""
    import numpy as np
    from datetime import datetime
    
    if len(twii_df) == 0:
        return
    
    # 最後一日資料
    last_date = twii_df.index[-1]
    last_row = twii_df.iloc[-1]
    
    # 基本行情
    open_price = last_row['Open']
    high_price = last_row['High']
    low_price = last_row['Low']
    close_price = last_row['Close']
    volume = last_row['Volume']
    
    # 技術指標
    ma20 = last_row.get('MA20', np.nan)
    ma60 = last_row.get('MA60', np.nan)
    ma120 = last_row.get('MA120', np.nan)
    ma240 = last_row.get('MA240', np.nan)
    k_value = last_row.get('K_raw', np.nan)
    
    # 體制狀態
    if regime_history and len(regime_history) > 0:
        last_regime = regime_history[-1]
        regime_mode = last_regime['regime']
        regime_ma120 = last_regime['ma120']
    else:
        regime_mode = 'BULL' if close_price >= ma120 else 'BEAR'
        regime_ma120 = ma120
    
    # 槓桿狀態
    leveraged_mode = bt1.equity_curve[-1].get('leveraged_mode', False) if bt1.equity_curve else False
    
    # 計算當前跌幅和觸發點
    peak_price = close_price
    if bt1.leverage_events:
        for event in bt1.leverage_events:
            if event['event'] == 'START':
                peak_price = event.get('peak_price', close_price)
    
    current_drawdown = (peak_price - close_price) / peak_price * 100 if peak_price > 0 else 0
    trigger_price = peak_price * (1 - bt1.LEVERAGE_THRESHOLD)
    distance_to_trigger = ((close_price - trigger_price) / close_price * 100) if not leveraged_mode else 0
    
    # AI 預測 (僅供參考)
    last_features = twii_df[feature_cols].iloc[-1].values.astype(np.float32)
    obs = np.nan_to_num(last_features, nan=0.0, posinf=1.0, neginf=-1.0).reshape(1, -1)
    
    buy_action_pred, _ = buy_model.predict(obs, deterministic=True)
    buy_probs = buy_model.policy.get_distribution(buy_model.policy.obs_to_tensor(obs)[0]).distribution.probs.detach().cpu().numpy()[0]
    buy_conf = float(buy_probs[1]) if buy_action_pred[0] == 1 else float(buy_probs[0])
    
    # KD 濾網檢查
    kd_pass = k_value < kd_threshold if not np.isnan(k_value) else True
    
    # 持倉計算
    ai_positions = bt1.open_positions
    dca_positions = bt1.dca_open_positions if hasattr(bt1, 'dca_open_positions') else []
    
    # 計算持倉價值
    ai_total_cost = sum(pos['cost'] for pos in ai_positions)
    ai_total_shares = sum(pos['shares'] for pos in ai_positions)
    ai_current_value = sum(
        pos['cost'] * (1 + (close_price / pos['buy_price'] - 1) * pos.get('leverage', 1))
        for pos in ai_positions
    )
    
    dca_total_cost = sum(pos['cost'] for pos in dca_positions)
    dca_total_shares = sum(pos['shares'] for pos in dca_positions)
    dca_current_value = sum(
        pos['cost'] * (1 + (close_price / pos['buy_price'] - 1) * pos.get('leverage', 1))
        for pos in dca_positions
    )
    
    total_cost = ai_total_cost + dca_total_cost
    total_current_value = ai_current_value + dca_current_value
    unrealized_profit = total_current_value - total_cost
    unrealized_pct = (unrealized_profit / total_cost * 100) if total_cost > 0 else 0
    
    remaining_cash = bt1.remaining_cash if hasattr(bt1, 'remaining_cash') else 0
    total_assets = total_current_value + remaining_cash
    
    # 2x 倉位統計
    ai_2x_count = sum(1 for pos in ai_positions if pos.get('leverage', 1) > 1)
    dca_2x_count = sum(1 for pos in dca_positions if pos.get('leverage', 1) > 1)
    total_2x = ai_2x_count + dca_2x_count
    
    # 關鍵特徵計算
    ma20_momentum = ((ma20 / twii_df.iloc[-5]['MA20'] - 1) * 100) if len(twii_df) >= 5 and not np.isnan(ma20) else 0
    regime_score = ((close_price / ma120 - 1) * 100) if not np.isnan(ma120) else 0
    short_divergence = ((close_price / ma20 - 1) * 100) if not np.isnan(ma20) else 0
    quarterly_distance = ((close_price / ma60 - 1) * 100) if not np.isnan(ma60) else 0
    yearly_position = ((close_price / ma240 - 1) * 100) if not np.isnan(ma240) else 0
    relative_volume = last_row.get('Volume_Ratio', 1.0)
    
    # 生成報告
    current_time = datetime.now().strftime('%H:%M:%S')
    
    lines = []
    lines.append("=" * 60)
    lines.append(f"📅 V5 回測結束日摘要 - {last_date.strftime('%Y-%m-%d')}")
    lines.append(f"⏰ 生成時間: {current_time}")
    lines.append("=" * 60)
    lines.append(f"📊 Open:  {open_price:,.2f}")
    lines.append(f"📈 High:  {high_price:,.2f}")
    lines.append(f"📉 Low:   {low_price:,.2f}")
    lines.append(f"💰 Close: {close_price:,.2f} (收盤)")
    lines.append(f"📦 Volume: {volume:.2f} 億元")
    lines.append("-" * 60)
    
    # 市場體制監控
    lines.append("📊 [市場體制監控] (MA120 動態濾網)")
    regime_icon = "🐂" if regime_mode == "BULL" else "🐻"
    lines.append(f"   體制: {regime_icon} {regime_mode} Mode")
    lines.append(f"   MA120: {regime_ma120:,.2f} | 收盤價: {close_price:,.2f}")
    
    if regime_mode == "BULL":
        lines.append("   濾網狀態: 🟢 未啟用 (牛市自由模式)")
    else:
        lines.append("   濾網狀態: 🔴 已啟用 (熊市防守模式)")
    
    lines.append("-" * 30)
    kd_status = "✅ 通過" if kd_pass else f"❌ 未通過 (K={k_value:.1f} >= {kd_threshold})"
    lines.append(f"   [KD 濾網] K(9,3): {k_value:.1f} | {kd_status}")
    lines.append("-" * 60)
    
    # 槓桿監控
    lines.append("⚡ [2x 槓桿監控] (Strategy 1)")
    lev_status = "🔥 ON (2倍槓桿)" if leveraged_mode else "❄️ OFF (1倍槓桿)"
    lines.append(f"   狀態: {lev_status}")
    lines.append(f"   高點: {peak_price:,.2f} | 目前跌幅: {current_drawdown:.2f}%")
    if not leveraged_mode:
        lines.append(f"   觸發: {trigger_price:,.2f} (距離: {distance_to_trigger:.2f}%)")
    lines.append("-" * 60)
    
    # 關鍵特徵
    lines.append("📐 [關鍵特徵]")
    lines.append(f"   MA20 動能: {ma20_momentum:+.2f}%")
    lines.append(f"   市場體制: {regime_score:+.2f}%")
    lines.append(f"   相對量能: {relative_volume:.2f}x")
    lines.append("-" * 60)
    
    # T+1 指令 (使用 pending_actions)
    lines.append("🚀 [指令：下個交易日開盤執行] (Instruction for Next Open)")
    
    # Strat 1 Actions
    pending_actions = getattr(bt1, 'pending_actions', [])
    if pending_actions:
         lines.append("   � Strategy 1 (2x Leverage on Drawdown) Actions:")
         for action in pending_actions:
             act_type = action['type']
             if act_type == 'BUY_DCA':
                 amt = action['amount']
                 est_shares = int(amt / close_price)
                 lines.append(f"      • � BUY DCA:  金額 ${amt:,.0f} (約 {est_shares} 股) | 槓桿 {action.get('leverage', 1.0):.1f}x")
             elif act_type == 'BUY_AI':
                 amt = action['amount']
                 est_shares = int(amt / close_price)
                 conf = action.get('confidence', 0)
                 lines.append(f"      • � BUY AI:   金額 ${amt:,.0f} (約 {est_shares} 股) | Conf {conf*100:.1f}% | 槓桿 {action.get('leverage', 1.0):.1f}x")
             elif act_type == 'SELL_AI':
                 pos = action['pos_ref']
                 buy_idx = pos['buy_idx']
                 buy_date_str = twii_df.index[buy_idx].strftime('%Y-%m-%d')
                 shares = pos['shares']
                 conf = action.get('confidence', 0)
                 is_stop = action.get('is_stop_loss', False)
                 status = "停損" if is_stop else "獲利/訊號"
                 lines.append(f"      • 🔴 SELL AI:  持倉 {buy_date_str} ({shares} 股) | Conf {conf*100:.1f}% | {status}")
             elif act_type == 'SELL_ALL_DCA':
                 lines.append(f"      • 🛑 SELL ALL DCA (DCA 連動停損)")
    else:
         lines.append("   📌 Strategy 1: No Actions (HOLD)")

    lines.append("")

    # Strat 2 Actions
    if bt2:
         pending_actions_2 = getattr(bt2, 'pending_actions', [])
         if pending_actions_2:
              lines.append("   📌 Strategy 2 (Shared Pool) Actions:")
              for action in pending_actions_2:
                  act_type = action['type']
                  if act_type == 'BUY_DCA':
                      amt = action['amount']
                      est_shares = int(amt / close_price)
                      lines.append(f"      • � BUY DCA:  金額 ${amt:,.0f} (約 {est_shares} 股)")
                  elif act_type == 'BUY_AI':
                      amt = action['amount']
                      est_shares = int(amt / close_price)
                      conf = action.get('confidence', 0)
                      lines.append(f"      • 🟢 BUY AI:   金額 ${amt:,.0f} (約 {est_shares} 股) | Conf {conf*100:.1f}%")
                  elif act_type == 'SELL_AI':
                      pos = action['pos_ref']
                      buy_idx = pos['buy_idx']
                      buy_date_str = twii_df.index[buy_idx].strftime('%Y-%m-%d')
                      shares = pos['shares']
                      conf = action.get('confidence', 0)
                      lines.append(f"      • 🔴 SELL AI:  持倉 {buy_date_str} ({shares} 股) | Conf {conf*100:.1f}%")
         else:
              lines.append("   📌 Strategy 2: No Actions (HOLD)")
    
    lines.append("-" * 60)
    
    # 持倉狀態
    lines.append("💼 [Strategy 1 持倉狀態]")
