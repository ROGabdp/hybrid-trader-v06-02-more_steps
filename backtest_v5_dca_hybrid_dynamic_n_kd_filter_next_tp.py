# =============================================================================
# Strategy 1: Shared Pool + 2x Leverage on Drawdown (大跌時啟動槓桿)
# =============================================================================
class LeveragedSharedPoolBacktester:
    """
    與 Strategy 2 相同的 Shared Pool 架構，但新增 2x 槓桿功能：
    - 當大盤從歷史高點下跌超過 8% 時，啟動 2x 槓桿模式 (與停損點一致)
    - 在 2x 模式期間買入的倉位（DCA 和 AI 都適用），其漲跌幅以 2 倍計算
    - 當大盤漲回到啟動 2x 模式的點位時，結束 2x 模式
    - 已買入的 2x 倉位維持 2x，直到該倉位被賣出
    """
    
    LEVERAGE_THRESHOLD = 0.08  # 下跌 8% 啟動槓桿 (與停損點一致)
    
    def __init__(self, buy_model, sell_model, yearly_capital=600_000,
                 dca_amount=50_000, ai_chunk_amount=50_000,
                 sell_threshold=0.6, buy_consensus_threshold=0.5, kd_threshold=20):
        self.buy_model = buy_model
        self.sell_model = sell_model
        self.yearly_capital = yearly_capital
        self.dca_amount = dca_amount
        self.ai_chunk_amount = ai_chunk_amount
        self.sell_threshold = sell_threshold
        self.buy_consensus_threshold = buy_consensus_threshold
        self.kd_threshold = kd_threshold
        
        self.trades = []
        self.equity_curve = []
        self.dca_buy_signals = []      
        self.ai_buy_signals = []       
        self.ai_sell_signals = []
        self.dca_sell_signals = []  # DCA 停損紀錄
        self.filtered_signals = []
        self.daily_confidence = []
        self.daily_action_summary = []
        self.open_positions = []
        self.total_invested = 0
        
        # 槓桿追蹤
        self.leverage_events = []  # 記錄槓桿啟動/結束事件
        self.leverage_periods = []  # 記錄槓桿期間 (start_date, end_date)

    def run(self, df: pd.DataFrame, feature_cols: list) -> dict:
        features = df[feature_cols].values.astype(np.float32)
        close_prices = df['Close'].values
        open_prices = df['Open'].values
        high_prices = df['High'].values
        dates = df.index
        
        # =========== 動態濾網：讀取必要數據 ===========
        # 1. Donchian Filter (for Bear Mode)
        if 'Signal_Buy_Filter' not in df.columns:
            print("[Warning] Signal_Buy_Filter missing, assuming True")
            donchian_signals = np.ones(len(df), dtype=bool)
        else:
            donchian_signals = df['Signal_Buy_Filter'].values.astype(bool)
        
        # 2. MA120 for Regime Detection
        if 'MA120' not in df.columns:
            print("[Error] MA120 not found in dataframe! Please update ptrl_hybrid_system.py")
            return {}
        ma120_values = df['MA120'].values
        
        # =========== 動態資金分配 ===========
        yearly_pool = 0
        dca_positions = []
        ai_positions = []
        
        current_year = None
        last_dca_month = None
        dynamic_chunk_amount = self.dca_amount
        
        # 2x 槓桿追蹤
        leveraged_mode = False
        leverage_trigger_price = 0
        peak_price = close_prices[0]
        current_leverage_start = None
        
        # 體制追蹤 (Dynamic Filter)
        bear_counter = 0     # 連續低於 MA120 天數
        current_regime = 'BULL' # 預設牛市
        self.regime_history = []
        self.filtered_signals = []
        
        self.pending_actions = [] # T+1 Execution Queue
        
        print(f"[Strategy 1] Period: {dates[0].strftime('%Y-%m-%d')} ~ {dates[-1].strftime('%Y-%m-%d')}")
        print(f"[Strategy 1] Dynamic Fund Allocation + 2x Leverage on Drawdown")
        print(f"[Strategy 1] Leverage Threshold: -{self.LEVERAGE_THRESHOLD*100:.0f}% from peak")
        print(f"[Strategy 1] MODE: DYNAMIC FILTER (Price < MA120 for 3 days -> Bear Mode)")
        print(f"[Strategy 1] EXECUTION: T+1 OPEN (Decisions on Close, Trade on Next Open)")

        for i in range(len(df)):
            date = dates[i]
            price = close_prices[i]
            open_price = open_prices[i]
            year = date.year
            month = date.month
            
            # =========== Phase 1: Execution (at T Open) ===========
            # 執行昨天決定要在今天開盤做的動作
            
            day_dca_shares = 0
            day_dca_leverage = 1.0
            day_sold_count = 0
            day_bought_shares = 0
            day_ai_leverage = 1.0
            day_dca_sold_count = 0
            
            # 用於標記哪些 action 已經執行
            next_pending_actions = [] # 未執行的（如果有）-> 理論上都應該執行
            
            if self.pending_actions:
                # 這裡的 yearly_pool 已經在 T-1 決策時做了預扣 (為了計算能否買進)，
                # 但實際股數要用 Open 算。如果 Open 暴漲導致錢不夠？
                # 策略：決策時用 Close 檢查資金，執行時用 Open 計算股數。
                # 資金流動：
                #   Buy: 決策時先扣除金額 (lock fund)，執行時多退少補？
                #   為了簡化：決策時"預計"使用資金。
                #   Better: 決策時只檢查 pool > threshold，不扣款。執行時才扣款。
                #   這樣比較安全。
                
                executed_pos_refs = [] # 記錄已賣出的 position reference，稍後從列表中移除

                for action in self.pending_actions:
                    act_type = action['type']
                    
                    if act_type == 'BUY_DCA':
                        fund = action['amount']
                        lev = action['leverage']
                        # 再次檢查資金
                        real_fund = min(fund, yearly_pool)
                        if real_fund > open_price: # 至少買1股
                            yearly_pool -= real_fund
                            shares = int(real_fund / open_price)
                            cost = shares * open_price
                            leftover = real_fund - cost
                            yearly_pool += leftover
                            
                            dca_positions.append({
                                'shares': shares, 
                                'buy_price': open_price, 
                                'buy_idx': i, 
                                'cost': cost,
                                'leverage': lev
                            })
                            day_dca_shares = shares
                            day_dca_leverage = lev
                            self.dca_buy_signals.append((date, open_price, shares, lev))
                            
                    elif act_type == 'BUY_AI':
                        fund = action['amount']
                        lev = action['leverage']
                        conf = action['confidence']
                        k_val = action['k_value']
                        
                        real_fund = min(fund, yearly_pool)
                        if real_fund > open_price:
                            yearly_pool -= real_fund
                            shares = int(real_fund / open_price)
                            cost = shares * open_price
                            leftover = real_fund - cost
                            yearly_pool += leftover
                            
                            ai_positions.append({
                                'shares': shares, 
                                'buy_price': open_price,
                                'highest_price': open_price, # [TP] Init Highest
                                'buy_idx': i, 
                                'cost': cost, 
                                'leverage': lev
                            })
                            self.ai_buy_signals.append({
                                'date': date, 
                                'price': open_price, 
                                'confidence': conf, 
                                'leverage': lev, 
                                'k_value': k_val,
                                'cost': cost,
                                'shares': shares
                            })
                            day_bought_shares = shares
                            day_ai_leverage = lev
                            
                    elif act_type == 'SELL_AI':
                        pos = action['pos_ref']
                        # 確認該持倉還在 (可能被其他邏輯清除了)
                        if pos in ai_positions and pos not in executed_pos_refs:
                            # 執行賣出
                            sell_conf = action['confidence']
                            is_stop = action['is_stop_loss']
                            
                            hold_days = i - pos['buy_idx']
                            base_return = open_price / pos['buy_price']
                            leveraged_return = 1 + (base_return - 1) * pos['leverage']
                            leveraged_value = pos['cost'] * leveraged_return
                            profit = leveraged_value - pos['cost']
                            
                            yearly_pool += leveraged_value
                            
                            self.trades.append({
                                'type': 'AI_S1', 
                                'return': leveraged_return - 1, 
                                'base_return': base_return - 1,
                                'profit': profit, 
                                'hold_days': hold_days,
                                'leverage': pos['leverage'],
                                'is_stop_loss': is_stop
                            })
                            self.ai_sell_signals.append({
                                'date': date, 
                                'price': open_price, 
                                'confidence': sell_conf, 
                                'leverage': pos['leverage'], 
                                'is_stop_loss': is_stop,
                                'cost': pos['cost'],
                                'proceeds': leveraged_value,
                                'shares': pos['shares']
                            })
                            executed_pos_refs.append(pos)
                            day_sold_count += 1

                    elif act_type == 'SELL_ALL_DCA':
                        # 執行清空 DCA
                        if dca_positions:
                            count = 0
                            for dca_pos in dca_positions:
                                hold_days = i - dca_pos['buy_idx']
                                base_return = open_price / dca_pos['buy_price']
                                leveraged_return = 1 + (base_return - 1) * dca_pos['leverage']
                                leveraged_value = dca_pos['cost'] * leveraged_return
                                profit = leveraged_value - dca_pos['cost']
                                
                                yearly_pool += leveraged_value
                                
                                self.trades.append({
                                    'type': 'DCA_STOPLOSS_S1',
                                    'return': leveraged_return - 1,
                                    'base_return': base_return - 1,
                                    'profit': profit,
                                    'hold_days': hold_days,
                                    'leverage': dca_pos['leverage'],
                                    'is_stop_loss': True
                                })
                                self.dca_sell_signals.append({
                                    'date': date, 
                                    'price': open_price, 
                                    'buy_price': dca_pos['buy_price'],
                                    'return': leveraged_return - 1,
                                    'leverage': dca_pos['leverage']
                                })
                                count += 1
                            day_dca_sold_count = count
                            dca_positions.clear()

                # 移除已賣出的 AI Position
                for p in executed_pos_refs:
                    if p in ai_positions:
                        ai_positions.remove(p)
                
                # 清空 Pending Actions (除非有未執行的特殊情況，目前全清空)
                self.pending_actions = []

            # =========== Phase 2: Updates (Regime, Leverage, Pool) ===========
            # 這些依賴 Close，屬於當日觀察
            
            # 2x 槓桿邏輯
            if not leveraged_mode:
                peak_price = max(peak_price, price)
            
            # [TP] Update Highest Price for AI Positions
            current_high = high_prices[i]
            for pos in ai_positions:
                if current_high > pos['highest_price']:
                    pos['highest_price'] = current_high
            
            if not leveraged_mode:
                if price < peak_price * (1 - self.LEVERAGE_THRESHOLD):
                    leveraged_mode = True
                    leverage_trigger_price = price
                    current_leverage_start = date
                    self.leverage_events.append({
                        'date': date, 'event': 'START', 'price': price,
                        'peak_price': peak_price, 
                        'drawdown': (peak_price - price) / peak_price * 100
                    })
                    print(f"  🔥 [{date.strftime('%Y-%m-%d')}] 2x 槓桿啟動! 價格 {price:,.0f}")
            else:
                if price >= leverage_trigger_price:
                    leveraged_mode = False
                    self.leverage_events.append({
                        'date': date, 'event': 'END', 'price': price,
                        'trigger_price': leverage_trigger_price
                    })
                    self.leverage_periods.append((current_leverage_start, date))
                    print(f"  ✅ [{date.strftime('%Y-%m-%d')}] 2x 槓桿結束!")
                    peak_price = price
                    current_leverage_start = None
            
            current_leverage = 2.0 if leveraged_mode else 1.0
            
            # 動態體制判斷
            ma120 = ma120_values[i]
            if np.isnan(ma120):
                regime = 'BULL'
            else:
                if price < ma120:
                    bear_counter += 1
                else:
                    bear_counter = 0
                
                if current_regime == 'BULL':
                    if bear_counter >= 3:
                        current_regime = 'BEAR'
                else:
                    if price >= ma120:
                        current_regime = 'BULL'
            
            self.regime_history.append({'date': date, 'regime': current_regime, 'price': price, 'ma120': ma120})
            
            is_bear_mode = (current_regime == 'BEAR')
            pass_donchian = bool(donchian_signals[i])
            pass_dynamic_filter = True
            if is_bear_mode and not pass_donchian:
                pass_dynamic_filter = False
            
            # 年度資金注入(年初)
            if current_year != year:
                current_year = year
                last_dca_month = None
                yearly_pool += self.yearly_capital
                self.total_invested += self.yearly_capital
                remaining_months = 13 - month
                dynamic_chunk_amount = yearly_pool / remaining_months if remaining_months > 0 else yearly_pool
                print(f"  [{year}] +${self.yearly_capital:,.0f} → Pool: ${yearly_pool:,.0f}")

            # 動態計算金額
            if last_dca_month != month:
                remaining_months = 13 - month
                if remaining_months > 0 and yearly_pool > 0:
                    dynamic_chunk_amount = yearly_pool / remaining_months
                else:
                    dynamic_chunk_amount = yearly_pool
                dynamic_chunk_amount = max(dynamic_chunk_amount, 10000)

            # =========== Phase 3: Decisions (Generate Actions for Tomorrow) ===========
            
            # DCA Decision (每月一次)
            # 使用 pending_actions 做標記
            if last_dca_month != month:
                last_dca_month = month
                # 決定明天買 DCA
                # amount = min(dynamic_chunk_amount, yearly_pool) # 注意: 這裡是預估，實際執行會再檢查
                # 這裡不鎖定金額，只發訊號。執行時才真正扣款。
                self.pending_actions.append({
                    'type': 'BUY_DCA',
                    'amount': dynamic_chunk_amount, # 意向金額
                    'leverage': current_leverage
                })
            
            # AI Decision
            obs = np.nan_to_num(features[i], nan=0.0, posinf=1.0, neginf=-1.0)
            
            day_action = 'HOLD' # For display (Close-based status)
            day_buy_conf = None
            day_sell_conf = None
            
            # Agent Consensus
            current_obs = obs.reshape(1, -1)
            buy_action_pred, _ = self.buy_model.predict(current_obs, deterministic=True)
            buy_probs = self.buy_model.policy.get_distribution(self.buy_model.policy.obs_to_tensor(current_obs)[0]).distribution.probs.detach().cpu().numpy()[0]
            current_buy_conf = float(buy_probs[1]) if buy_action_pred[0] == 1 else float(buy_probs[0])
            day_buy_conf = current_buy_conf
            
            # Check Sells / Stop Loss
            # 注意: 這裡的 current_pos 都是"今天已經持有"的。
            # 如果今天剛買入? 照邏輯是 Phase 1 執行買入，所以現在已經在 ai_positions 裡了。
            # 可以馬上評估賣出嗎? 可以。T+0 買入，收盤評估，T+1 賣出。這是合理的。
            
            max_sell_conf_today = 0
            stop_loss_signal_generated = False
            
            # 用一個 list 收集要賣出的 pos object
            positions_to_sell = [] 
            
            for pos in ai_positions:
                # 如果已經在 pending_actions 裡排隊要賣，就跳過?
                # 我們每次 loop 都清空 pending_actions，所以新的 pending 都是空的 (除非我們要做多日排程，但這裡是 T+1)
                # 所以每個 loop 開始時 pending 為空。Phase 3 產生新的 pending。
                
                # 計算槓桿後報酬
                buy_p = pos['buy_price']
                current_return = price / buy_p # Close / Buy
                leveraged_return = 1 + (current_return - 1) * pos['leverage']
                
                sell_obs = np.concatenate([obs, [leveraged_return]]).astype(np.float32).reshape(1, -1)
                action, _ = self.sell_model.predict(sell_obs, deterministic=True)
                
                sell_probs = self.sell_model.policy.get_distribution(self.sell_model.policy.obs_to_tensor(sell_obs)[0]).distribution.probs.detach().cpu().numpy()[0]
                sell_conf = float(sell_probs[1]) if action[0] == 1 else float(sell_probs[0])
                max_sell_conf_today = max(max_sell_conf_today, sell_conf)
                
                log_entry = {'date': date, 'status': 'holding', 'price': price, 'sell_conf': sell_conf, 'buy_conf': current_buy_conf, 'action': 'hold', 'leverage': pos['leverage']}
                self.daily_confidence.append(log_entry)
                
                # [TP] Complex Stop Logic
                # 1. Hard Stop
                hard_stop_price = pos['buy_price'] * (1 - HARD_STOP_PCT)
                is_hard_stop = (open_price <= hard_stop_price) # Check against Open/Close? Logic loop uses Close usually, but execution is Next Open. 
                # Let's use Close for decision trigger as per design "Decisions on Close".
                is_hard_stop = price <= hard_stop_price

                # 2. Trailing Stop
                # Use highest_price tracked so far
                pos_highest = pos['highest_price']
                max_profit_pct = (pos_highest - pos['buy_price']) / pos['buy_price']
                
                # Determine callback
                callback = TRAIL_CALLBACK_HIGH if max_profit_pct > TRAIL_HIGH_PROFIT_THR else TRAIL_CALLBACK_BASE
                trail_stop_price = pos_highest * (1 - callback)
                
                is_trail_active = max_profit_pct >= TRAIL_ACTIVATION
                is_trail_stop = is_trail_active and (price <= trail_stop_price)
                
                # Combined
                is_stop_loss = is_hard_stop or is_trail_stop
                # is_stop_loss = leveraged_return < 0.92 # OLD Logic Removed
                
                is_sell_signal = (action[0] == 1 and sell_conf > self.sell_threshold)
                
                # Consensus
                is_consensus_hold = False
                if is_sell_signal and not is_stop_loss:
                    if buy_action_pred[0] == 1 and current_buy_conf > self.buy_consensus_threshold:
                        is_consensus_hold = True
                
                if (is_sell_signal and not is_consensus_hold) or is_stop_loss:
                    # 產生賣出訊號 -> 明天開盤執行
                    log_entry['action'] = 'SELL_SIGNAL'
                    positions_to_sell.append({
                        'type': 'SELL_AI',
                        'pos_ref': pos,
                        'confidence': sell_conf,
                        'is_stop_loss': is_stop_loss
                    })
                    if is_stop_loss:
                        stop_loss_signal_generated = True
                    
                    day_action = 'SELL_SIGNAL'
                    day_sell_conf = sell_conf
            
            # 將賣出訊號加入 pending
            for p_action in positions_to_sell:
                self.pending_actions.append(p_action)
            
            # DCA 連動停損
            if stop_loss_signal_generated and len(dca_positions) > 0:
                print(f"  🛑 [{date.strftime('%Y-%m-%d')}] AI 停損訊號! 排程明天清空 DCA")
