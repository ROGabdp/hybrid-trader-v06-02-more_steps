def fetch_intraday_ohlc(ticker: str = "^TWII") -> tuple:
    """
    從證交所盤中即時 API 下載當日 OHLC 資料
    """
    import requests
    
    print(f"\n[Download] 正在從證交所盤中 API 下載即時資料...")
    url = "https://mis.twse.com.tw/stock/api/getStockInfo.jsp?ex_ch=tse_t00.tw"
    headers = {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36',
        'Accept': 'application/json',
        'Referer': 'https://mis.twse.com.tw/stock/index.jsp'
    }
    
    try:
        r = requests.get(url, headers=headers, timeout=10)
        r.raise_for_status()
        data = r.json()
        msg_array = data.get('msgArray', [])
        
        if not msg_array:
            print("[Error] 證交所 API 無資料 (可能非交易時段)")
            return None
        
        item = msg_array[0]
        raw_date = item.get('d', '')
        if len(raw_date) == 8:
            date_str = f"{raw_date[:4]}-{raw_date[4:6]}-{raw_date[6:8]}"
        else:
            date_str = datetime.now().strftime('%Y-%m-%d')
        
        o = float(item.get('o', 0))
        h = float(item.get('h', 0))
        l = float(item.get('l', 0))
        z = float(item.get('z', 0))
        time_str = item.get('t', 'N/A')
        
        print(f"  📅 日期: {date_str}")
        print(f"  ⏰ 時間: {time_str}")
        print(f"  📈 Open: {o:.2f}")
        print(f"  📊 High: {h:.2f}")
        print(f"  📉 Low: {l:.2f}")
        print(f"  💰 即時價: {z:.2f}")
        
        return (date_str, o, h, l, z)
        
    except Exception as e:
        print(f"[Error] 取得盤中資料失敗: {e}")
        return None


