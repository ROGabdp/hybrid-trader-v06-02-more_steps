    print("\n" + "=" * 60)
    print(f"🎯 Step 3: V5 策略推論 (動態濾網 + KD < {kd_threshold})")
    print(f"   ⚙️ Consensus: Sell Threshold > {sell_threshold} | Buy Veto > {buy_consensus_threshold}")
    print("=" * 60)
    
    from stable_baselines3 import PPO
    latest = df.iloc[-1]
    
    # 如果沒傳入 current_price，從 df 取得
    if current_price is None:
        current_price = float(latest['Close'])
    
    # 計算體制狀態
    regime_status = calculate_regime_status(df)
    regime = regime_status['regime']
    filter_active = regime_status['filter_active']
    donchian_pass = regime_status['donchian_pass']
    
    # 顯示體制狀態
    regime_icon = "🐂" if regime == 'BULL' else "🐻"
    print(f"  [體制] {regime_icon} {regime} Mode (熊市天數: {regime_status['bear_days']})")
