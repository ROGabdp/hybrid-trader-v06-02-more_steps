def interactive_select_csv(csv_files: list, default_index: int = -1) -> str:
    """
    使用方向鍵選擇 CSV 檔案
    
    Args:
        csv_files: CSV 檔案路徑列表
        default_index: 預設選擇的索引 (-1 表示最後一個)
    
    Returns:
        選擇的檔案路徑
    """
    import msvcrt
    
    sorted_files = sorted(csv_files)
    current_index = default_index if default_index >= 0 else len(sorted_files) - 1
    
    def render_menu():
        print("\n📂 請選擇回測 CSV (↑↓ 選擇, Enter 確認):")
        print("-" * 50)
        for i, f in enumerate(sorted_files):
            basename = os.path.basename(f)
            if i == current_index:
                print(f"  ▶ {basename} ◀")
            else:
                print(f"    {basename}")
        print("-" * 50)
    
    # 清除並顯示選單
    render_menu()
    
    while True:
        if msvcrt.kbhit():
            key = msvcrt.getch()
            
            # 方向鍵在 Windows 會先返回 0xe0 或 0x00
            if key in (b'\xe0', b'\x00'):
                arrow = msvcrt.getch()
                if arrow == b'H':  # 上
                    current_index = max(0, current_index - 1)
                elif arrow == b'P':  # 下
                    current_index = min(len(sorted_files) - 1, current_index + 1)
                
                # 清除螢幕並重繪
                print("\033[F" * (len(sorted_files) + 4), end='')  # 移動游標上移
                render_menu()
            
            elif key == b'\r':  # Enter
                print(f"\n✅ 已選擇: {os.path.basename(sorted_files[current_index])}")
                return sorted_files[current_index]
            
            elif key == b'\x1b':  # ESC
                print("\n⏹️ 取消選擇，使用預設 (最新)")
                return sorted_files[-1]


