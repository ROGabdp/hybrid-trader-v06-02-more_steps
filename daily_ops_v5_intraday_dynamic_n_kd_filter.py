def load_latest_backtest_status(backtest_start: str = None, interactive: bool = False) -> dict:
    """
    讀取回測 daily_action_strat1 CSV (Strategy 1: Leverage Mode)，取得持倉狀態與槓桿資訊
    
    Args:
        backtest_start: 可選，指定回測起始日期 (格式: YYYYMMDD 或 YYYY-MM-DD)
        interactive: 若為 True，則顯示互動式選單讓用戶選擇
    """
    import glob
    
    result = {
        'found': False,
        'csv_file': None,
        'last_date': None,
        'ai_position_count': 0,
        'dca_position_count': 0,
        'total_position_count': 0,
        'leveraged_mode': False,
        'current_leverage': 1.0,
        'positions_2x': 0,
        'peak_price': 0.0,
        'last_action': 'N/A',
        'last_note': 'N/A'
    }
    
    # 尋找 daily_action CSV (Strat 1)
    pattern = os.path.join(BACKTEST_RESULTS_PATH, 'daily_action_strat1_*.csv')
    csv_files = glob.glob(pattern)
    
    if not csv_files:
        print(f"[Backtest] 找不到回測結果: {pattern}")
        return result
    
    sorted_files = sorted(csv_files)
    
    # 選擇檔案
    if interactive and len(sorted_files) > 1:
        # 互動式選擇
        target_csv = interactive_select_csv(csv_files)
    elif backtest_start:
        # 命令列指定
        start_normalized = backtest_start.replace('-', '')
        matched = [f for f in csv_files if f'_{start_normalized}_' in f]
        if matched:
            target_csv = matched[0]
            print(f"[Backtest] 使用指定起始日: {backtest_start}")
        else:
            print(f"[Backtest] ⚠️ 找不到起始日 {backtest_start}，使用最新檔案")
            target_csv = sorted_files[-1]
    else:
        # 預設使用最新
        target_csv = sorted_files[-1]
        if len(sorted_files) > 1:
            print(f"[Backtest] 找到 {len(sorted_files)} 個回測結果，使用最新:")
        
    print(f"[Backtest] 讀取: {os.path.basename(target_csv)}")
    
    try:
        df = pd.read_csv(target_csv)
        if len(df) == 0:
            return result
        
        last_row = df.iloc[-1]
        
        # 計算目前的 Peak Price (依照 Strategy 1 邏輯)
        # 邏輯: 非槓桿模式時，更新最高價；槓桿模式時，最高價鎖定 (作為出場基準)
        current_peak_price = 0
        for _, row in df.iterrows():
            if 'leveraged_mode' in row:
                is_leveraged = bool(row['leveraged_mode'])
                price = float(row['price'])
                if not is_leveraged:
                    if price > current_peak_price:
                        current_peak_price = price
            else:
                current_peak_price = max(current_peak_price, float(row['price']))

        # Update Result
        result.update({
            'found': True,
            'csv_file': os.path.basename(target_csv),
            'last_date': last_row.get('date', 'N/A'),
            'ai_position_count': int(last_row.get('ai_position_count', 0)),
            'dca_position_count': int(last_row.get('dca_position_count', 0)),
            'total_position_count': int(last_row.get('total_position_count', 0)),
            'leveraged_mode': bool(last_row.get('leveraged_mode', False)),
            'current_leverage': float(last_row.get('current_leverage', 1.0)),
            'positions_2x': int(last_row.get('positions_2x', 0)),
            'peak_price': current_peak_price,
            'last_action': last_row.get('ai_action', 'N/A'),
            'last_note': last_row.get('note', 'N/A'),
            'open_positions': []
        })
        
        # 嘗試讀取 open_positions CSV (Strat 1)
        pos_csv = target_csv.replace('daily_action_strat1_', 'open_positions_strat1_')
        if os.path.exists(pos_csv):
            pos_df = pd.read_csv(pos_csv)
            result['open_positions'] = pos_df.to_dict('records')
            print(f"  AI 持倉: {len(result['open_positions'])} 筆")
        else:
            print(f"  ⚠️ 找不到 AI 持倉檔案: {os.path.basename(pos_csv)}")
        
        # 讀取 DCA 持倉 CSV
        dca_pos_csv = target_csv.replace('daily_action_strat1_', 'open_positions_dca_strat1_')
        result['dca_positions_list'] = []
        if os.path.exists(dca_pos_csv):
            dca_pos_df = pd.read_csv(dca_pos_csv)
            result['dca_positions_list'] = dca_pos_df.to_dict('records')
            print(f"  DCA 持倉: {len(result['dca_positions_list'])} 筆")
        
        # 讀取剩餘現金池
        cash_file = target_csv.replace('daily_action_strat1_', 'remaining_cash_strat1_').replace('.csv', '.json')
        result['remaining_cash'] = 0
        if os.path.exists(cash_file):
            with open(cash_file, 'r', encoding='utf-8') as f:
                cash_info = json.load(f)
                result['remaining_cash'] = cash_info.get('remaining_cash', 0)
            print(f"  剩餘現金: ${result['remaining_cash']:,.0f}")
        
        leverage_status = "🔥 ON (2x)" if result['leveraged_mode'] else "OFF (1x)"
        print(f"  最後日期: {result['last_date']}")
        print(f"  持倉狀態: 總{result['total_position_count']}倉 (DCA{result['dca_position_count']} + AI{result['ai_position_count']})")
        print(f"  槓桿狀態: {leverage_status} | Peak: {current_peak_price:,.2f}")
        
    except Exception as e:
        print(f"[Error] 讀取回測 CSV 失敗: {e}")
    
    return result


