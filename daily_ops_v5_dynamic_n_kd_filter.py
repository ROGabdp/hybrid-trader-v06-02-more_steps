def calculate_regime_status(df: pd.DataFrame, lookback: int = 3) -> dict:
    """
    計算目前市場體制 (Bull/Bear Mode) 和濾網狀態
    
    邏輯:
    - 熊市模式: 價格 < MA120 連續 `lookback` 天
    - 熊市時啟用 Donchian 濾網 (Close > 10日 High)
    - 牛市時無濾網限制
    """
    last_rows = df.tail(lookback + 1)
    
    # 檢查 MA120 是否存在
    if 'MA120' not in df.columns:
        return {
            'regime': 'BULL',
            'bear_days': 0,
            'ma120': 0,
            'donchian_pass': True,
            'filter_active': False,
            'reason': 'MA120 不存在，預設牛市'
        }
    
    last_row = df.iloc[-1]
    close_price = float(last_row['Close'])
    ma120 = float(last_row.get('MA120', 0))
    donchian_pass = bool(last_row.get('Signal_Buy_Filter', False))
    
    # 計算連續低於 MA120 的天數
    bear_days = 0
    for i in range(len(last_rows) - 1, -1, -1):
        row = last_rows.iloc[i]
        if float(row['Close']) < float(row.get('MA120', 0)):
            bear_days += 1
        else:
            break
    
    # 判定體制
    if bear_days >= lookback:
        regime = 'BEAR'
        filter_active = True
        reason = f'價格 < MA120 連續 {bear_days} 天，啟用 Donchian 濾網'
    else:
        regime = 'BULL'
        filter_active = False
        reason = f'牛市模式，無濾網限制'
    
    return {
        'regime': regime,
        'bear_days': bear_days,
        'ma120': ma120,
        'close': close_price,
        'donchian_pass': donchian_pass,
        'filter_active': filter_active,
        'reason': reason
    }


def v5_inference(workspace: dict, df: pd.DataFrame, open_positions: list = None, close_price: float = None,
                 sell_threshold: float = 0.6, buy_consensus_threshold: float = 0.5, kd_threshold: float = 90) -> dict:
    """
    V5 策略推論 (動態濾網)
    
    Args:
        workspace: 工作區資訊
        df: 特徵 DataFrame
        open_positions: 從回測讀取的 AI 持倉清單 (含 buy_price, buy_date)
        close_price: 今日收盤價 (用於計算各持倉報酬率)
        sell_threshold: 賣出信心門檻 (預設 0.5)
        buy_consensus_threshold: 買入共識門檻 (預設 0.8)
    """
    print("\n" + "=" * 60)
    print(f"🎯 Step 3: V5 策略推論 (動態濾網 + KD < {kd_threshold})")
    print(f"   ⚙️ Consensus: Sell Threshold > {sell_threshold} | Buy Veto > {buy_consensus_threshold}")
    print("=" * 60)
    
    from stable_baselines3 import PPO
    latest = df.iloc[-1]
    
    # 如果沒傳入 close_price，從 df 取得
    if close_price is None:
        close_price = float(latest['Close'])
    
    # 計算體制狀態
    regime_status = calculate_regime_status(df)
    regime = regime_status['regime']
    filter_active = regime_status['filter_active']
    donchian_pass = regime_status['donchian_pass']
    
    # 顯示體制狀態
    regime_icon = "🐂" if regime == 'BULL' else "🐻"
    print(f"  [體制] {regime_icon} {regime} Mode (熊市天數: {regime_status['bear_days']})")
    print(f"  [MA120] {regime_status.get('ma120', 0):,.2f} | Close: {close_price:,.2f}")
    filter_state = "ON (啟用中)" if filter_active else "OFF (未啟用)"
    donchian_state = "✅通過" if donchian_pass else "❌未通過"
    print(f"  [濾網] 動態濾網: {filter_state} | Donchian: {donchian_state}")
    
    # 保留 filter 資訊
    signal_buy_filter = donchian_pass
    
    features = np.array([latest.get(col, 0.0) for col in core_system.FEATURE_COLS], dtype=np.float32).reshape(1, -1)
    features = np.nan_to_num(features, nan=0.0, posinf=1.0, neginf=-1.0)
    
    # 載入 V5 模型
    buy_path = os.path.join(V5_MODEL_PATH, 'ppo_buy_twii_final.zip')
    sell_path = os.path.join(V5_MODEL_PATH, 'ppo_sell_twii_final.zip')
    
    if not os.path.exists(buy_path):
        return {'error': 'V5 Model not found', 'filter_signal': signal_buy_filter, 'regime_status': regime_status}

    try:
        buy_agent = PPO.load(buy_path)
        sell_agent = PPO.load(sell_path)
        
        # ===== Buy Agent =====
        b_act, _ = buy_agent.predict(features, deterministic=True)
        b_obs = buy_agent.policy.obs_to_tensor(features)[0]
        b_prob = buy_agent.policy.get_distribution(b_obs).distribution.probs.detach().cpu().numpy()[0]
        
        ai_action = 'BUY' if b_act[0] == 1 else 'WAIT'
        buy_prob = float(b_prob[1]) if b_act[0] == 1 else float(b_prob[0])
        
        # 準備 KD 資料
        current_k = float(latest.get('K_raw', 50))  # 若無則預設50
        pass_kd_filter = current_k < kd_threshold

        # 動態濾網邏輯: 
        # 1. 熊市時啟用 Donchian 濾網
        # 2. 隨時啟用 KD 濾網 (必須 < kd_threshold)
        
        filter_status_str = ""
        pass_regime_filter = True # 預設通過
        
        if filter_active:
            # 熊市模式: 必須通過 Donchian
            if not donchian_pass:
                pass_regime_filter = False
                filter_status_str += "🚫熊市濾網未過 "
        
        if not pass_kd_filter:
            filter_status_str += f"🚫KD過高({current_k:.1f}>={kd_threshold}) "
            
        pass_all_filters = pass_regime_filter and pass_kd_filter

        if ai_action == 'BUY':
            if pass_all_filters:
                buy_signal = 'BUY'
                filter_note = f"✅通過 (KD={current_k:.1f})"
            else:
                buy_signal = 'FILTERED'
                filter_note = f"🚫被濾網擋下: {filter_status_str}"
        else:
            buy_signal = ai_action
            filter_note = "-"
        
        # 牛市/熊市 狀態補充
        if not filter_active:
            filter_note += " (牛市)"
            
        print(f"  [KD ] K(9,3): {current_k:.2f} (Threshold: {kd_threshold}) -> {'✅PASS' if pass_kd_filter else '❌FAIL'}")
        
        print(f"  [V5] AI 判斷: {ai_action} ({buy_prob:.1%})")
        print(f"  [V5] 最終決策: {buy_signal} | {filter_note}")
        
        # ===== Sell Agent (真實持倉分析) =====
        position_decisions = []
        
        if open_positions and len(open_positions) > 0:
            print(f"  [V5] 分析 {len(open_positions)} 筆 AI 持倉...")
            
            for pos in open_positions:
                buy_price = float(pos.get('buy_price', 0))
                buy_date = pos.get('buy_date', 'N/A')
                
                if buy_price > 0:
                    # 計算真實報酬率
                    current_return = close_price / buy_price
                    return_pct = (current_return - 1) * 100
                    
                    # 構建 Sell Agent 的觀察值 (特徵 + 報酬率)
                    s_feat = np.concatenate([features[0], [current_return]]).reshape(1, -1).astype(np.float32)
                    s_act, _ = sell_agent.predict(s_feat, deterministic=True)
                    
                    # 取得機率分布以計算信心
                    s_obs = sell_agent.policy.obs_to_tensor(s_feat)[0]
                    s_prob = sell_agent.policy.get_distribution(s_obs).distribution.probs.detach().cpu().numpy()[0]
                    
                    sell_action = 'SELL' if s_act[0] == 1 else 'HOLD'
                    sell_conf = float(s_prob[1]) if s_act[0] == 1 else float(s_prob[0])
                    
                    # 判斷是否觸發停損 (硬性規則: -8%)
                    triggered_stop_loss = current_return < 0.92
                    
                    # 🔥 Agent Consensus Logic
                    # 賣出條件: (AI=SELL & Conf > Threshold) 且 (沒有被 Buy Agent 強力否決)
                    # 只有在非停損的情況下，Buy Agent 才能否決
                    
                    is_sell_signal = (s_act[0] == 1 and sell_conf > sell_threshold)
                    is_consensus_hold = False
                    veto_reason = ""
                    
                    if is_sell_signal and not triggered_stop_loss:
                        # 🔥 只有當 Buy Agent 真心想買 (Action=1) 且信心夠高時，才否決賣出
                        # NOTE: 在 inference 中，ai_action 已經被轉換為 'BUY' 或 'WAIT'
                        if ai_action == 'BUY' and buy_prob > buy_consensus_threshold:
                            is_consensus_hold = True
                            veto_reason = f"🚫 Consensus Veto (Buy Conf {buy_prob:.1%} > {buy_consensus_threshold})"
                            print(f"    -> Sell Signal Vetoed! {veto_reason}")

                    final_action = 'HOLD'
                    if triggered_stop_loss:
                        final_action = 'SELL'
                    elif is_sell_signal and not is_consensus_hold:
                        final_action = 'SELL'
                    
                    position_decisions.append({
                        'buy_date': buy_date,
                        'buy_price': buy_price,
                        'current_return': current_return,
                        'return_pct': return_pct,
                        'action': sell_action,
                        'confidence': sell_conf,
                        'triggered_stop_loss': triggered_stop_loss,
                        'is_consensus_hold': is_consensus_hold,
                        'veto_reason': veto_reason,
                        'final_action': final_action
                    })
        else:
            print(f"  [V5] 無 AI 持倉，跳過 Sell Agent 分析")
        
        return {
            'filter_signal': pass_all_filters,
            'kd_value': current_k,
            'kd_pass': pass_kd_filter,
            'buy_decision': buy_signal,
            'buy_confidence': buy_prob * 100,
            'buy_action': int(b_act[0]),
            'ai_action': ai_action,
            'position_decisions': position_decisions,
            'regime_status': regime_status  # 體制狀態
        }
    except Exception as e:
        print(f"  [Error] V5 Inference: {e}")
        return {'error': str(e), 'filter_signal': signal_buy_filter, 'regime_status': regime_status}


