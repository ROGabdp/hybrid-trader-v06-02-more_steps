def interactive_select_csv(csv_files: list, default_index: int = -1) -> str:
    """
    使用方向鍵選擇 CSV 檔案
    """
    import msvcrt
    
    if default_index < 0:
        default_index = len(csv_files) + default_index
    
    current = default_index
    
    def render_menu():
        print("\033[H\033[J", end="")  # Clear screen
        print("📂 請選擇回測 CSV (↑↓ 選擇, Enter 確認):")
        print("-" * 50)
        for i, f in enumerate(csv_files):
            marker = "  ▶ " if i == current else "    "
            suffix = " ◀" if i == current else ""
            print(f"{marker}{os.path.basename(f)}{suffix}")
        print("-" * 50)
    
    while True:
        render_menu()
        key = msvcrt.getch()
        
        if key == b'\xe0':  # Arrow key prefix
            key2 = msvcrt.getch()
            if key2 == b'H':  # Up
                current = (current - 1) % len(csv_files)
            elif key2 == b'P':  # Down
                current = (current + 1) % len(csv_files)
        elif key == b'\r':  # Enter
            print(f"\n✅ 已選擇: {os.path.basename(csv_files[current])}")
            return csv_files[current]


