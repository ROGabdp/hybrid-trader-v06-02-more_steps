def calculate_pure_dca(df: pd.DataFrame, monthly_amount: float = 50_000):
    close_prices = df['Close'].values
    dates = df.index
    shares = 0
    total_invested = 0
    equity_curve = []
    last_month = None
    leftover_cash = 0  # 累積的零頭
    current_year = None
    
    for i in range(len(df)):
        date = dates[i]
        price = close_prices[i]
        year = date.year
        month = date.month
        
        # 年度變更 - 重置 leftover (新年度開始)
        if current_year != year:
            current_year = year
            leftover_cash = 0  # 新年度開始，重置零頭池
        
