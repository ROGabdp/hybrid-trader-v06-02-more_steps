                if today_open < limit_price:
                    fund = amount
                    if yearly_pool >= fund:
                        yearly_pool -= fund
                        shares = int(fund / today_open)
                        cost = shares * today_open
                        leftover = fund - cost
                        yearly_pool += leftover
                        
                        ai_positions.append({'shares': shares, 'buy_price': today_open, 'buy_idx': i, 'cost': cost})
                        
